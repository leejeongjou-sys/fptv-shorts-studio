// 처음 채울 문서들로 펼치기
export function seedDocs(mapKey) {
  const M = MAPS[mapKey];
  const out = [];
  const counter = {};
  const push = (x, parent) => {
    const id = `${mapKey}-${out.length.toString(36)}-${Math.random().toString(36).slice(2, 6)}`;
    counter[x.stage] = (counter[x.stage] || 0) + 1;
    out.push({ id, map: mapKey, stage: x.stage, order: counter[x.stage] * 10, parent: parent || null, title: x.title, body: x.body, type: x.type, createdAt: Date.now(), by: '초기 설정' });
    x.kids.forEach((k) => push(k, id));
  };
  M.nodes.forEach((x) => push(x, null));
  return out;
}
